/* Задача 2.Да се състави програма, която намира най-малката нечетна цифра в зададено
цяло число.*/
#include <iostream>

int main(void)
{
    int n, c, k {10}; 
    std::cout << "Въведете число: "; std::cin >> n; 
    while(n > 0)
    {
        c = n % 10; 
        if(c % 2 != 0)
        {
            if(c < k) k = c; 
        }
        n = n / 10; 
    }
    std::cout << "Най-малката нечетна цифра: " << k << "\n";
    return 0; 
}